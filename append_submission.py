"""
Append a new submission (parsed from a GitHub Issue Form) as a row to the
correct _data/*.csv file. Reads the parsed form data from the ISSUE_JSON env
var (JSON string keyed by each form field's `id`) and the target library
from the LIBRARY env var ("cbs", "liss", or "port").

Uses Python's csv module for writing so quoting/escaping and UTF-8 encoding
(accents, special characters) are handled correctly -- this is the whole
point of not asking contributors to hand-edit the CSV.
"""

import csv
import json
import os

CSV_PATHS = {
    "cbs": "_data/cbs.csv",
    "liss": "_data/liss.csv",
    "port": "_data/port.csv",
}

# (issue form field id, CSV column name) pairs, in no particular order --
# writing is done by column name via DictWriter, so order here doesn't need
# to match the CSV header order.
FIELD_MAPS = {
    "cbs": [
        ("title", "title"),
        ("cbs_project_nr", "CBS_project_nr"),
        ("project_lead", "project_lead"),
        ("orcid", "orcid"),
        ("odissei_grant", "ODISSEI_grant"),
        ("publication", "publication"),
        ("data_used", "data used"),
        ("data_produced", "data produced"),
        ("code", "code"),
        ("programming_language", "programming language"),
        # data_design is intentionally excluded -- it's auto-generated by
        # enrich_cbs.py from the Knowledge Graph, never submitted by hand.
    ],
    "liss": [
        ("title", "title"),
        ("project_lead", "project_lead"),
        ("orcid", "orcid"),
        ("odissei_grant", "ODISSEI_grant"),
        ("publication_type", "publication type"),
        ("publication", "publication"),
        ("data", "data"),
        ("link_data", "link_data"),
        ("code", "code"),
        ("programming_language", "programming language"),
    ],
    "port": [
        ("platform", "platform"),
        ("method", "method"),
        ("extractionscript", "extractionscript"),
        ("analysis", "analysis"),
        ("project_lead", "project_lead"),
        ("orcid", "orcid"),
        ("participants", "participants"),
        ("data", "data"),
        ("publication", "publication"),
        ("odissei_grant", "odissei_grant"),
    ],
}


def clean(value):
    """Strip whitespace and normalize Issue Forms' empty-answer placeholder."""
    if value is None:
        return ""
    value = value.strip()
    if value.lower() in ("_no response_", "no response"):
        return ""
    return value


def main():
    library = os.environ["LIBRARY"]
    issue_data = json.loads(os.environ["ISSUE_JSON"])

    csv_path = CSV_PATHS[library]
    field_map = FIELD_MAPS[library]

    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        fieldnames = reader.fieldnames

    new_row = {name: "" for name in fieldnames}
    for field_id, column_name in field_map:
        new_row[column_name] = clean(issue_data.get(field_id))

    with open(csv_path, "a", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writerow(new_row)

    print(f"Appended new row to {csv_path}:")
    print(new_row)


if __name__ == "__main__":
    main()
